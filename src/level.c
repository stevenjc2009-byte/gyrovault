int level_load(int index, Level *out)
{
    Level tmp;
    int starts = 0, goals = 0;
    int x, y;

    if (!out || index < 0 || index >= LEVEL_COUNT)
        return -1;

    memset(&tmp, 0, sizeof(tmp));
    tmp.name = LEVEL_NAMES[index];

    for (y = 0; y < LEVEL_H; y++) {
        const char *row = LEVEL_MAPS[index][y];
        if (!row || strlen(row) != (size_t)LEVEL_W)
            return -1;
        for (x = 0; x < LEVEL_W; x++) {
            unsigned char cell;
            switch (row[x]) {
            case '#': cell = CELL_WALL; break;
            case '.': cell = CELL_FLOOR; break;
            case 'O': cell = CELL_HOLE; break;
            case 'G': cell = CELL_GOAL; goals++; break;
            case 'S':
                cell = CELL_FLOOR;
                starts++;
                tmp.start_x = (float)(x * CELL_PX + CELL_PX / 2);
                tmp.start_y = (float)(y * CELL_PX + CELL_PX / 2);
                break;
            default: return -1;
            }
            if ((x == 0 || y == 0 || x == LEVEL_W - 1 || y == LEVEL_H - 1) && cell != CELL_WALL)
                return -1;
            tmp.cells[y][x] = cell;
        }
    }

    if (starts != 1 || goals != 1)
        return -1;

    *out = tmp;
    return 0;
}

CellType level_cell(const Level *lv, int cx, int cy)
{
    if (!lv || cx < 0 || cy < 0 || cx >= LEVEL_W || cy >= LEVEL_H)
        return CELL_WALL;
    return (CellType)lv->cells[cy][cx];
}
